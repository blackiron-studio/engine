const UNKNOWN = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"];

/** Normalise a character to the glyph key that exists in the font. */
export function glyphKey(ch: string): string {
  const up = ch.toUpperCase();
  if (up in G) return up;
  return "?";
}

export function glyphRows(ch: string): string[] {
  return G[glyphKey(ch)] ?? UNKNOWN;
}

export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in G;
}

export const FONT_CHARS: string[] = Object.keys(G);

/** Width in pixels of a single-line string at scale 1. */
export function measureText(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * FONT_ADVANCE - 1) * scale;
}
